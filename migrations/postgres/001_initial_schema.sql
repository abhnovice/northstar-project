CREATE TABLE IF NOT EXISTS aimcat_schedules (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, provider TEXT NOT NULL DEFAULT 'TIME', series TEXT NOT NULL DEFAULT 'AIMCAT',
